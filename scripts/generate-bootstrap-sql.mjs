#!/usr/bin/env node
/**
 * Generates prisma/bootstrap.sql — the schema plus the master skills and roles
 * — as one file that can be pasted into a browser SQL console.
 *
 * This exists because `prisma db push` needs a direct connection on port 5432,
 * which many campus and office networks block outbound. Neon's SQL editor runs
 * over HTTPS, so this file is a way to set up the database from anywhere.
 *
 *   npm run db:sql
 */

import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "prisma", "schema.prisma");
const seedPath = join(root, "prisma", "seed.ts");
const enumsPath = join(root, "src", "lib", "enums.ts");
const outPath = join(root, "prisma", "bootstrap.sql");

// --- 1. the schema, as PostgreSQL DDL -------------------------------------

// The real schema is never modified: a postgres-flavoured copy goes in a
// temporary directory, so an interrupted run cannot leave the working schema
// pointing at the wrong provider.
const asPostgres = readFileSync(schemaPath, "utf8").replace(
  /(datasource db \{[^}]*?provider\s*=\s*)"[a-z]+"/s,
  '$1"postgresql"',
);

const tempDir = mkdtempSync(join(tmpdir(), "fmt-schema-"));
const tempSchema = join(tempDir, "schema.prisma");

let ddl;
try {
  writeFileSync(tempSchema, asPostgres);
  ddl = execFileSync(
    "npx",
    [
      "prisma",
      "migrate",
      "diff",
      "--from-empty",
      "--to-schema-datamodel",
      tempSchema,
      "--script",
    ],
    { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
  );
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}

// --- 2. master data, read from the seed so it cannot drift ---------------

const seed = readFileSync(seedPath, "utf8");
const skillsBlock = seed.slice(
  seed.indexOf("const SKILLS: Array<[string, string]> = ["),
  seed.indexOf("type DemoUser"),
);

const skills = [...skillsBlock.matchAll(/\["([^"]+)",\s*"([A-Z_]+)"\]/g)].map(
  ([, name, category]) => ({ name, category }),
);

const enums = readFileSync(enumsPath, "utf8");
const rolesBlock = enums.slice(
  enums.indexOf("export const STANDARD_ROLES = ["),
  enums.indexOf("] as const;", enums.indexOf("export const STANDARD_ROLES = [")),
);
const roles = [...rolesBlock.matchAll(/"([^"]+)"/g)].map(([, name]) => name);

if (skills.length === 0 || roles.length === 0) {
  console.error("Could not read the skills or roles out of the seed files.");
  process.exit(1);
}

/** cuid-shaped id, since Prisma generates these client-side, not in the database. */
function cuid() {
  return `c${randomBytes(12).toString("hex")}`;
}

const escape = (value) => value.replace(/'/g, "''");

const inserts = [
  "-- ---------------------------------------------------------------------------",
  "-- Master data: the skill and role tables every form and search reads from.",
  "-- Safe to re-run: existing names are left untouched.",
  "-- ---------------------------------------------------------------------------",
  "",
  "INSERT INTO \"Skill\" (\"id\", \"name\", \"category\", \"approved\", \"createdAt\") VALUES",
  skills
    .map(
      (s) =>
        `  ('${cuid()}', '${escape(s.name)}', '${s.category}', true, CURRENT_TIMESTAMP)`,
    )
    .join(",\n") + "\nON CONFLICT (\"name\") DO NOTHING;",
  "",
  "INSERT INTO \"Role\" (\"id\", \"name\") VALUES",
  roles.map((name) => `  ('${cuid()}', '${escape(name)}')`).join(",\n") +
    "\nON CONFLICT (\"name\") DO NOTHING;",
  "",
];

// --- 3. write the combined file ------------------------------------------

const header = [
  "-- ===========================================================================",
  "-- FindMyTeammate — database bootstrap for PostgreSQL",
  "--",
  "-- Generated by `npm run db:sql`. Do not edit by hand; edit the Prisma schema",
  "-- or the seed and regenerate.",
  "--",
  "-- Use this when `prisma db push` cannot reach port 5432 (many campus and",
  "-- office networks block it outbound). Paste the whole file into Neon's SQL",
  "-- Editor, or any browser Postgres console, and run it.",
  "--",
  `-- Contains: the full schema, ${skills.length} skills and ${roles.length} team roles.`,
  "-- Does NOT contain demo accounts — those are development-only.",
  "-- ===========================================================================",
  "",
].join("\n");

writeFileSync(outPath, `${header}${ddl}\n${inserts.join("\n")}\n`);

console.log(`Wrote prisma/bootstrap.sql`);
console.log(`  schema + ${skills.length} skills + ${roles.length} roles`);
